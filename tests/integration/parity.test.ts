import { readFileSync } from "node:fs";
import path from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { importHubWorkbook } from "@/application/hub/import";
import { dashboard, projectsView, registerExtras } from "@/application/hub/views";
import { listRows } from "@/application/hub/registers";
import { listPeriods } from "@/application/hub/periods";
import { admin, resetDb } from "./helpers";

/**
 * Workbook parity. The workbook is the specification, so the Hub's own calculations are compared
 * with the numbers Excel last stored in the sample file. The fixture is generated by
 * `npx tsx scripts/parity-fixture.ts`; this test never opens Excel.
 *
 * Known and accepted differences, each with its reason:
 * - QIC D9 "GIS Resources Region": the workbook cell is typed over its formula (Dubai) while the
 *   people on the project sit in South Africa. The Hub follows the formula, and the team is to
 *   correct the sheet (report 2026-11-02, parity table).
 * - Anything that depends on TODAY(): Excel calculated the file on 30-Oct-2026, so Overdue, RAG
 *   and Days Overdue are compared only where they do not depend on the current date.
 */
const fixtureFile = path.join(process.cwd(), "tests/fixtures/workbook-parity.json");
type Cached = string | number | boolean | null;
interface Fixture {
  source: string;
  dashboard: Record<string, Cached>;
  rows: { sheet: string; key: string; values: Record<string, Cached> }[];
}
const fx: Fixture = JSON.parse(readFileSync(fixtureFile, "utf8"));
const REGION_TYPED_OVER = "QIC D9";

const pct = (n: number | null | undefined) => (n === null || n === undefined ? null : n / 100);

describe("workbook parity", () => {
  let rows: Awaited<ReturnType<typeof projectsView>>["rows"];
  let dash: Awaited<ReturnType<typeof dashboard>>;

  beforeAll(async () => {
    await resetDb();
    const a = await admin();
    await importHubWorkbook(
      a,
      { name: "hub.xlsx", buffer: readFileSync(path.join(process.cwd(), "tests/fixtures/GIS_Practice_Hub_sample.xlsx")) },
      false,
    );
    // Compare on the period Excel calculated for, not on today's period, so the test does not
    // depend on the date it runs.
    const period = (await listPeriods()).find((p) => p.startDate === fx.dashboard.periodStart);
    rows = (await projectsView(a, period?.id)).rows;
    dash = await dashboard(a, period?.id);
  });

  it("reads the fixture that was generated from the sample", () => {
    expect(fx.source).toBe("GIS_Practice_Hub_sample.xlsx");
    expect(Object.keys(fx.dashboard).length).toBeGreaterThan(3);
    expect(fx.rows.length).toBeGreaterThan(8);
  });

  it("matches the Dashboard tiles Excel calculated", () => {
    const d = fx.dashboard;
    if (d.totalProjects !== undefined) expect(dash.kpis.totalProjects).toBe(d.totalProjects);
    if (d.activeProjects !== undefined) expect(dash.kpis.activeProjects).toBe(d.activeProjects);
    if (d.notStarted !== undefined) expect(dash.kpis.notStarted).toBe(d.notStarted);
    if (d.atRisk !== undefined) expect(dash.kpis.atRisk).toBe(d.atRisk);
    if (d.openRisks !== undefined) expect(dash.kpis.openRisks).toBe(d.openRisks);
    if (d.openRfis !== undefined) expect(dash.kpis.openRfis).toBe(d.openRfis);
    if (d.openClientComments !== undefined) expect(dash.kpis.openClientComments).toBe(d.openClientComments);
    if (d.submissionsThisPeriod !== undefined) expect(dash.kpis.submissionsThisPeriod).toBe(d.submissionsThisPeriod);
    // E10 is a share in Excel (0.6) and a percentage in the Hub (60).
    if (d.teamUtilisation !== undefined) expect(pct(dash.kpis.teamUtilisation)).toBeCloseTo(d.teamUtilisation as number, 5);
  });

  it("matches the period the Dashboard was calculated for", () => {
    if (fx.dashboard.periodStart) expect(dash.period?.startDate).toBe(fx.dashboard.periodStart);
    if (fx.dashboard.periodEnd) expect(dash.period?.endDate).toBe(fx.dashboard.periodEnd);
  });

  it("matches every cached derived cell of the Projects sheet", () => {
    const mismatches: string[] = [];
    for (const r of fx.rows.filter((r) => r.sheet === "Projects")) {
      // The workbook writes "ML04 / RTA ..." on the Projects sheet and "ML04 - RTA ..." on its tab.
      const row = rows.find((p) => p.name === r.key || p.name.replace(/ - /g, " / ") === r.key);
      if (!row) {
        mismatches.push(`${r.key}: not imported`);
        continue;
      }
      for (const [header, want] of Object.entries(r.values)) {
        let got: Cached | undefined;
        switch (header) {
          case "CRS Total":
            got = row.crsTotal;
            break;
          case "RFI Open":
            got = row.rfi.open;
            break;
          case "RFI Closed":
            got = row.rfi.closed;
            break;
          case "RFI Total":
            got = row.rfi.total;
            break;
          case "GIS Delivered / Approved":
            got = row.delivered;
            break;
          case "GIS In Progress":
            got = row.inProgress;
            break;
          case "Next Milestone":
            got = row.milestone.text;
            break;
          case "Submissions This Period":
            got = row.submissionsThisPeriod;
            break;
          case "Utilisation %":
            got = pct(row.utilisation);
            break;
          case "GIS Resources Region":
            if (r.key === REGION_TYPED_OVER) continue; // typed over the formula, see the note above
            got = row.region;
            break;
          default:
            continue;
        }
        const same =
          typeof want === "number" && typeof got === "number"
            ? Math.abs(want - got) < 1e-6
            : String(got ?? "") === String(want ?? "");
        if (!same) mismatches.push(`${r.key} ${header}: workbook ${JSON.stringify(want)}, Hub ${JSON.stringify(got)}`);
      }
    }
    expect(mismatches).toEqual([]);
  });

  it("matches the QA/QC score and result Excel calculated", async () => {
    const extraOf = await registerExtras("qaqc");
    const a = await admin();
    const qaqc = await listRows(a, "qaqc", {});
    const mismatches: string[] = [];
    for (const r of fx.rows.filter((r) => r.sheet === "QAQC")) {
      const row = qaqc.find((q) => String(q.projectName ?? "") === r.key);
      if (!row) {
        mismatches.push(`${r.key}: not imported`);
        continue;
      }
      const extra = extraOf(row as unknown as Record<string, unknown>) as Record<string, string>;
      for (const [header, want] of Object.entries(r.values)) {
        if (header === "Score") {
          const got = Number(String(extra.Score ?? "").replace(/[^\d.]/g, ""));
          // Excel keeps the share (0.625) and shows "63 %"; the Hub shows the same rounded
          // percentage, so the comparison allows the half point the rounding costs.
          if (Math.abs(got / 100 - (want as number)) > 0.0051) mismatches.push(`${r.key} Score: ${want} vs ${extra.Score}`);
        }
        if (header === "Result" && String(extra.Result ?? "") !== String(want)) {
          mismatches.push(`${r.key} Result: ${want} vs ${extra.Result}`);
        }
      }
    }
    expect(mismatches).toEqual([]);
  });
});
